import assert from "node:assert/strict";
import { execFile as execFileCallback } from "node:child_process";
import { chmod, mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import test from "node:test";
import {
  CommitSigningKeyError,
  generateCommitSigningKeyPair,
  parseOpenSshPrivateKey,
  readImportablePrivateKey,
} from "../../lib/commit-signing/key-material";

const execFile = promisify(execFileCallback);

test("a generated signing key is a real OpenSSH Ed25519 key", async () => {
  const pair = generateCommitSigningKeyPair();

  assert.match(pair.privateKey, /^-----BEGIN OPENSSH PRIVATE KEY-----/);
  assert.match(pair.privateKey, /-----END OPENSSH PRIVATE KEY-----\n?$/);
  assert.match(pair.publicKey, /^ssh-ed25519 [A-Za-z0-9+/=]+ /);
  assert.match(pair.fingerprint, /^SHA256:[A-Za-z0-9+/]+$/);

  const parsed = parseOpenSshPrivateKey(pair.privateKey);
  assert.ok(parsed);
  assert.equal(parsed.publicKey, pair.publicKey);
  assert.equal(parsed.fingerprint, pair.fingerprint);
});

test("ssh-keygen derives the same public key from the generated private key", async () => {
  const pair = generateCommitSigningKeyPair();
  const dir = await mkdtemp(path.join(tmpdir(), "mogplex-signing-key-"));
  const keyPath = path.join(dir, "id_ed25519");
  await writeFile(keyPath, pair.privateKey);
  await chmod(keyPath, 0o600);

  const derived = await execFile("ssh-keygen", ["-y", "-f", keyPath]);
  const derivedKey = derived.stdout.trim().split(" ")[1];
  const generatedKey = pair.publicKey.split(" ")[1];
  assert.equal(derivedKey, generatedKey);
});

test("git signs a commit with a generated key", async () => {
  const pair = generateCommitSigningKeyPair();
  const dir = await mkdtemp(path.join(tmpdir(), "mogplex-signing-git-"));
  const keyPath = path.join(dir, "id_ed25519");
  await writeFile(keyPath, pair.privateKey);
  await chmod(keyPath, 0o600);

  const repo = path.join(dir, "repo");
  await execFile("git", ["init", "--quiet", repo]);
  await execFile("git", ["-C", repo, "config", "gpg.format", "ssh"]);
  await execFile("git", ["-C", repo, "config", "user.signingkey", keyPath]);
  await execFile("git", ["-C", repo, "config", "commit.gpgsign", "true"]);
  await execFile("git", ["-C", repo, "config", "user.name", "Test"]);
  await execFile("git", [
    "-C",
    repo,
    "config",
    "user.email",
    "test@example.com",
  ]);
  await execFile("git", [
    "-C",
    repo,
    "commit",
    "--allow-empty",
    "-m",
    "signed",
  ]);

  const raw = await execFile("git", ["-C", repo, "cat-file", "commit", "HEAD"]);
  assert.ok(
    raw.stdout.includes("BEGIN SSH SIGNATURE"),
    "the commit must carry an SSH signature"
  );
});

test("importing rejects text that is not an OpenSSH private key", () => {
  assert.equal(parseOpenSshPrivateKey("not a key"), null);
  assert.throws(
    () =>
      readImportablePrivateKey("-----BEGIN OPENSSH PRIVATE KEY-----\nnope\n"),
    CommitSigningKeyError
  );
});

test("importing accepts a key generated by ssh-keygen", async () => {
  const dir = await mkdtemp(path.join(tmpdir(), "mogplex-signing-import-"));
  const keyPath = path.join(dir, "id_ed25519");
  await execFile("ssh-keygen", ["-t", "ed25519", "-N", "", "-f", keyPath]);

  const { readFile } = await import("node:fs/promises");
  const armored = await readFile(keyPath, "utf8");
  const parsed = readImportablePrivateKey(armored);

  assert.match(parsed.publicKey, /^ssh-ed25519 /);
  assert.match(parsed.fingerprint, /^SHA256:/);
});
